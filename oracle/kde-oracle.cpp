#include <kcolorutils.h>
#include <kguiaddons_version.h>
#include <vector>

#include "grid.h"

static QColor col(const grid_color_t &g)
{
    return QColor::fromRgba64(QRgba64::fromRgba64(g.r, g.g, g.b, g.a));
}

static void put(FILE *f, const QColor &c)
{
    const QRgba64 v = c.rgba64();
    std::fprintf(f, "\t%u\t%u\t%u\t%u", v.red(), v.green(), v.blue(), v.alpha());
}

static void put(FILE *f, double d)
{
    std::fprintf(f, "\t%.17g", d);
}

static FILE *open_table(const char *dir, const char *name, const char *cols)
{
    char path[1024];
    std::snprintf(path, sizeof path, "%s/%s.tsv", dir, name);
    FILE *f = std::fopen(path, "w");
    if (!f) {
        std::perror(path);
        return nullptr;
    }
    std::fprintf(f, "# generated by oracle/kde-oracle.cpp; do not edit\n");
    std::fprintf(f,
                 "# KF6GuiAddons %s, Qt %s, %s\n",
                 KGUIADDONS_VERSION_STRING,
                 qVersion(),
                 QDate::currentDate().toString(Qt::ISODate).toUtf8().constData());
    std::fprintf(f, "# columns: %s\n", cols);
    return f;
}

struct Case {
    int kind;     // 0 explicit keys, 1 empty config as Disabled, 2 empty config as Inactive
    int inactive; // 1: the ColorEffects:Inactive group and QPalette::Inactive
    int enable, intensity, color, contrast;
    double iamt, camt, cmt;
    int er, eg, eb;
};

static std::vector<Case> effect_cases()
{
    std::vector<Case> v;
    v.push_back({1, 0, 1, 2, 0, 1, 0.10, 0.0, 0.65, 56, 56, 56});
    v.push_back({2, 1, 0, 0, 1, 2, 0.0, -0.9, 0.25, 112, 111, 110});
    v.push_back({0, 0, 0, 2, 1, 1, 0.3, 0.3, 0.3, 10, 20, 30});      // Enable=false
    v.push_back({0, 1, 1, 2, 1, 2, 0.0, -0.9, 0.25, 112, 111, 110}); // inactive defaults, enabled
    for (int it = 1; it <= 3; it++)
        for (double a : {0.1, 0.5, 1.2})
            v.push_back({0, 0, 1, it, 0, 0, a, 0.0, 0.0, 0, 0, 0});
    for (int ce = 1; ce <= 3; ce++)
        for (double a : {-0.9, 0.3, 1.0})
            v.push_back({0, 0, 1, 0, ce, 0, 0.0, a, 0.0, 200, 50, 30});
    for (int ct = 1; ct <= 2; ct++)
        for (double a : {0.25, 0.65})
            v.push_back({0, 0, 1, 0, 0, ct, 0.0, 0.0, a, 0, 0, 0});
    v.push_back({0, 0, 1, 9, 9, 9, 0.5, 0.5, 0.5, 90, 90, 90});   // unknown codes
    v.push_back({0, 0, 1, 2, 3, 2, 0.1, 0.5, 0.65, 200, 50, 30}); // everything at once
    return v;
}

static QString rgb8(const QColor &c)
{
    return QStringLiteral("%1,%2,%3").arg(c.red()).arg(c.green()).arg(c.blue());
}

static const QColor role_text[6] = {QColor(61, 174, 233),
                                    QColor(41, 128, 185),
                                    QColor(127, 140, 141),
                                    QColor(218, 68, 83),
                                    QColor(246, 116, 0),
                                    QColor(39, 174, 96)};

// cin, a: input rgba16 columns. Pairs for mix and tint come from col(i) and col(j).
int main(int argc, char **argv)
{
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s <output-dir>\n", argv[0]);
        return 2;
    }
    static grid_color_t g[GRID_MAX_COLORS];
    const int n = grid_colors(g);
    int i, j, k;

    FILE *f = open_table(
        argv[1], "hcy", "r g b a | luma hue(getHcy h) chroma y | hcyColor(h c y a) r g b a");
    if (!f)
        return 1;
    for (i = 0; i < n; i++) {
        const QColor c = col(g[i]);
        qreal h, ch, y, a;
        KColorUtils::getHcy(c, &h, &ch, &y, &a);
        std::fprintf(f, "%u\t%u\t%u\t%u", g[i].r, g[i].g, g[i].b, g[i].a);
        put(f, KColorUtils::luma(c));
        put(f, h);
        put(f, ch);
        put(f, y);
        put(f, KColorUtils::hcyColor(h, ch, y, a));
        std::fprintf(f, "\n");
    }
    std::fclose(f);

    f = open_table(argv[1],
                   "utils",
                   "op(0 contrast 1 lighten 2 darken 3 shade 4 mix 5 tint) | c1 rgba16 | c2 rgba16 "
                   "(or 0) | k1 | k2 | result: r g b a (contrast: value)");
    if (!f)
        return 1;
    for (i = 0; i < n; i++) {
        const QColor c = col(g[i]);
        j = (i * 37 + 11) % n;
        const QColor d = col(g[j]);
        std::fprintf(f,
                     "0\t%u\t%u\t%u\t%u\t%u\t%u\t%u\t%u\t0\t0",
                     g[i].r,
                     g[i].g,
                     g[i].b,
                     g[i].a,
                     g[j].r,
                     g[j].g,
                     g[j].b,
                     g[j].a);
        put(f, KColorUtils::contrastRatio(c, d));
        std::fprintf(f, "\n");
        for (k = 0; k < GRID_AMOUNTS; k++) {
            const double a = grid_amounts[k], b = grid_amounts[(k + 3) % GRID_AMOUNTS];
            const int op[3] = {1, 2, 3};
            for (int o = 0; o < 3; o++) {
                std::fprintf(f,
                             "%d\t%u\t%u\t%u\t%u\t0\t0\t0\t0\t%.17g\t%.17g",
                             op[o],
                             g[i].r,
                             g[i].g,
                             g[i].b,
                             g[i].a,
                             a,
                             b);
                put(f,
                    o == 0   ? KColorUtils::lighten(c, a, b)
                    : o == 1 ? KColorUtils::darken(c, a, b)
                             : KColorUtils::shade(c, a, b));
                std::fprintf(f, "\n");
            }
            std::fprintf(f,
                         "4\t%u\t%u\t%u\t%u\t%u\t%u\t%u\t%u\t%.17g\t0",
                         g[i].r,
                         g[i].g,
                         g[i].b,
                         g[i].a,
                         g[j].r,
                         g[j].g,
                         g[j].b,
                         g[j].a,
                         a);
            put(f, KColorUtils::mix(c, d, a));
            std::fprintf(f, "\n");
            std::fprintf(f,
                         "5\t%u\t%u\t%u\t%u\t%u\t%u\t%u\t%u\t%.17g\t0",
                         g[i].r,
                         g[i].g,
                         g[i].b,
                         g[i].a,
                         g[j].r,
                         g[j].g,
                         g[j].b,
                         g[j].a,
                         a);
            put(f, KColorUtils::tint(c, d, a));
            std::fprintf(f, "\n");
        }
    }
    std::fclose(f);

    f = open_table(argv[1], "shade", "c rgba16 | role | contrast | chromaAdjust | result rgba16");
    if (!f)
        return 1;
    {
        static const double contrasts[] = {-2.0, -0.5, 0.0, 0.7, 1.0, 5.0};
        static const double chromas[] = {0.0, 0.2};
        for (i = 0; i < n; i++) {
            const QColor c = col(g[i]);
            for (int role = 0; role < 5; role++)
                for (double ct : contrasts)
                    for (double ca : chromas) {
                        std::fprintf(f,
                                     "%u\t%u\t%u\t%u\t%d\t%.17g\t%.17g",
                                     g[i].r,
                                     g[i].g,
                                     g[i].b,
                                     g[i].a,
                                     role,
                                     ct,
                                     ca);
                        put(f,
                            KColorScheme::shade(
                                c, static_cast<KColorScheme::ShadeRole>(role), ct, ca));
                        std::fprintf(f, "\n");
                    }
        }
    }
    std::fclose(f);
    f = open_table(
        argv[1],
        "effects",
        "kind(0 explicit,1 empty Disabled,2 empty Inactive) enable intensity iamt color camt er eg "
        "eb contrast cmt | bg rgba16 | fg rgba16 | effected bg rgba16 | effected fg rgba16");
    FILE *fr = open_table(argv[1],
                          "roles",
                          "effected NormalBackground | effected text | calculated background, all "
                          "rgba16 (6 KDE roles per input)");
    if (!f || !fr)
        return 1;
    for (const Case &cs : effect_cases()) {
        for (i = 0; i < 343; i += 5) {
            const QColor bg = col(g[i]), fg = col(g[(i * 37 + 11) % 343]);
            KSharedConfigPtr cfg = KSharedConfig::openConfig(QString(), KConfig::SimpleConfig);
            KConfigGroup w(cfg, QStringLiteral("Colors:Window"));
            w.writeEntry("BackgroundNormal", rgb8(bg));
            w.writeEntry("ForegroundNormal", rgb8(fg));
            const char *keys[6] = {"ForegroundActive",
                                   "ForegroundLink",
                                   "ForegroundVisited",
                                   "ForegroundNegative",
                                   "ForegroundNeutral",
                                   "ForegroundPositive"};
            for (int r = 0; r < 6; r++)
                w.writeEntry(keys[r], rgb8(role_text[r]));
            const QPalette::ColorGroup state =
                cs.inactive ? QPalette::Inactive : QPalette::Disabled;
            if (cs.kind == 0) {
                KConfigGroup e(cfg,
                               cs.inactive ? QStringLiteral("ColorEffects:Inactive")
                                           : QStringLiteral("ColorEffects:Disabled"));
                e.writeEntry("Enable", cs.enable != 0);
                e.writeEntry("IntensityEffect", cs.intensity);
                e.writeEntry("ColorEffect", cs.color);
                e.writeEntry("ContrastEffect", cs.contrast);
                e.writeEntry("IntensityAmount", cs.iamt);
                e.writeEntry("ColorAmount", cs.camt);
                e.writeEntry("ContrastAmount", cs.cmt);
                e.writeEntry("Color", QColor(cs.er, cs.eg, cs.eb));
            }
            KColorScheme scheme(state, KColorScheme::Window, cfg);
            std::fprintf(f,
                         "%d\t%d\t%d\t%.17g\t%d\t%.17g\t%d\t%d\t%d\t%d\t%.17g",
                         cs.kind,
                         cs.enable,
                         cs.intensity,
                         cs.iamt,
                         cs.color,
                         cs.camt,
                         cs.er,
                         cs.eg,
                         cs.eb,
                         cs.contrast,
                         cs.cmt);
            std::fprintf(f,
                         "\t%u\t%u\t%u\t%u\t%u\t%u\t%u\t%u",
                         g[i].r,
                         g[i].g,
                         g[i].b,
                         g[i].a,
                         g[(i * 37 + 11) % 343].r,
                         g[(i * 37 + 11) % 343].g,
                         g[(i * 37 + 11) % 343].b,
                         g[(i * 37 + 11) % 343].a);
            put(f, scheme.background(KColorScheme::NormalBackground).color());
            put(f, scheme.foreground(KColorScheme::NormalText).color());
            std::fprintf(f, "\n");
            static const KColorScheme::ForegroundRole fgr[6] = {KColorScheme::ActiveText,
                                                                KColorScheme::LinkText,
                                                                KColorScheme::VisitedText,
                                                                KColorScheme::NegativeText,
                                                                KColorScheme::NeutralText,
                                                                KColorScheme::PositiveText};
            static const KColorScheme::BackgroundRole bgr[6] = {KColorScheme::ActiveBackground,
                                                                KColorScheme::LinkBackground,
                                                                KColorScheme::VisitedBackground,
                                                                KColorScheme::NegativeBackground,
                                                                KColorScheme::NeutralBackground,
                                                                KColorScheme::PositiveBackground};
            for (int r = 0; r < 6; r++) {
                const QRgba64 nb =
                    scheme.background(KColorScheme::NormalBackground).color().rgba64();
                std::fprintf(fr, "%u\t%u\t%u\t%u", nb.red(), nb.green(), nb.blue(), nb.alpha());
                put(fr, scheme.foreground(fgr[r]).color());
                put(fr, scheme.background(bgr[r]).color());
                std::fprintf(fr, "\n");
            }
        }
    }
    std::fclose(f);
    std::fclose(fr);
    return 0;
}
