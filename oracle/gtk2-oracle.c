/* Writes the hls golden table from GTK2's own _gtk_style_shade.
 * Usage: gtk2-oracle <output-dir>
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
#include <stdio.h>
#include <time.h>

#include "grid.h"
#include "gtk2-shade.h"

int main(int argc, char **argv)
{
    static grid_color_t g[GRID_MAX_COLORS];
    static const double ks[] = {0.0, 0.5, 0.7, 1.0, 1.3, 2.0};
    char path[1024];
    FILE *f;
    int n = grid_colors(g), i, j;
    time_t now = time(NULL);
    char date[16];

    if (argc != 2) {
        fprintf(stderr, "usage: %s <output-dir>\n", argv[0]);
        return 2;
    }
    snprintf(path, sizeof path, "%s/hls.tsv", argv[1]);
    f = fopen(path, "w");
    if (!f) {
        perror(path);
        return 1;
    }
    strftime(date, sizeof date, "%Y-%m-%d", localtime(&now));
    fprintf(f, "# generated by oracle/gtk2-oracle.c; do not edit\n");
    fprintf(f, "# GTK+ 2.24 gtkstyle.c (commit 6863194), %s\n", date);
    fprintf(f,
            "# columns: kind(0 shade, 1 mid, 2 text_aa) | a rgb16 | b rgb16 (0 for shade) | k | "
            "result rgb16\n");
    for (i = 0; i < n; i++) {
        GdkColor a, r;
        a.red = g[i].r;
        a.green = g[i].g;
        a.blue = g[i].b;
        for (j = 0; j < (int)(sizeof ks / sizeof ks[0]); j++) {
            _gtk_style_shade(&a, &r, ks[j]);
            fprintf(f,
                    "0\t%u\t%u\t%u\t0\t0\t0\t%.17g\t%u\t%u\t%u\n",
                    a.red,
                    a.green,
                    a.blue,
                    ks[j],
                    r.red,
                    r.green,
                    r.blue);
        }
        {
            /* mid and text_aa: integer average of a and its pair. */
            GdkColor b;
            j = (i * 37 + 11) % n;
            b.red = g[j].r;
            b.green = g[j].g;
            b.blue = g[j].b;
            fprintf(f,
                    "1\t%u\t%u\t%u\t%u\t%u\t%u\t0\t%u\t%u\t%u\n",
                    a.red,
                    a.green,
                    a.blue,
                    b.red,
                    b.green,
                    b.blue,
                    (a.red + b.red) / 2,
                    (a.green + b.green) / 2,
                    (a.blue + b.blue) / 2);
            fprintf(f,
                    "2\t%u\t%u\t%u\t%u\t%u\t%u\t0\t%u\t%u\t%u\n",
                    a.red,
                    a.green,
                    a.blue,
                    b.red,
                    b.green,
                    b.blue,
                    (a.red + b.red) / 2,
                    (a.green + b.green) / 2,
                    (a.blue + b.blue) / 2);
        }
    }
    fclose(f);
    return 0;
}
